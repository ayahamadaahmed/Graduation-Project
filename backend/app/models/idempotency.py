import uuid
from datetime import datetime

from sqlalchemy import (
    DateTime,
    Index,
    String,
    UnicodeText,
    UniqueConstraint,
    text,
)

from sqlalchemy.orm import (
    Mapped,
    mapped_column,
)

from app.db.base import Base


class IdempotencyRequest(Base):
    """
    Stores idempotency information for
    write operations such as:

    - create_booking
    - cancel_booking
    - reschedule_booking

    The business operation and its
    idempotency result are committed
    in the same SQL Server transaction.
    """

    __tablename__ = "idempotency_requests"

    __table_args__ = (
        UniqueConstraint(
            "tenant_id",
            "operation",
            "idempotency_key",
            name=(
                "uq_idempotency_"
                "tenant_operation_key"
            ),
        ),
        Index(
            "ix_idempotency_created_at",
            "created_at",
        ),
    )

    # =========================================
    # Primary Key
    # =========================================

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=lambda: str(
            uuid.uuid4()
        ),
    )

    # =========================================
    # Tenant / Provider Scope
    # =========================================

    # Currently stores the validated internal
    # provider UUID as a string.
    #
    # Example:
    # 5eb0e74d-5cb6-4b16-b91e-b40344250d68
    #
    # We do not trust the raw X-Tenant-ID
    # directly at the business/database layer.
    tenant_id: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )

    # =========================================
    # Operation
    # =========================================

    # Examples:
    #
    # create_booking
    # cancel_booking
    # reschedule_booking
    operation: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
    )

    # =========================================
    # Idempotency Key
    # =========================================

    # Generated/supplied by the caller.
    #
    # The same:
    #
    # tenant
    # + operation
    # + key
    #
    # can only exist once.
    idempotency_key: Mapped[str] = (
        mapped_column(
            String(128),
            nullable=False,
        )
    )

    # =========================================
    # Request Hash
    # =========================================

    # SHA-256 hash of the canonical request.
    #
    # Used to detect:
    #
    # same key + same request
    #     -> replay
    #
    # same key + different request
    #     -> conflict
    #
    # Raw national ID must not be stored here.
    request_hash: Mapped[str] = (
        mapped_column(
            String(64),
            nullable=False,
        )
    )

    # =========================================
    # Status
    # =========================================

    # Current values:
    #
    # pending
    # completed
    # failed
    status: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="pending",
        server_default=text(
            "'pending'"
        ),
    )

    # =========================================
    # Cached Response
    # =========================================

    # Successful response is serialized as JSON
    # and stored as NVARCHAR(MAX) on SQL Server.
    #
    # UnicodeText is important because responses
    # can contain Arabic doctor/service names.
    response_body: Mapped[
        str | None
    ] = mapped_column(
        UnicodeText,
        nullable=True,
    )

    # =========================================
    # Error
    # =========================================

    # Optional normalized error code.
    #
    # We do not store sensitive exception
    # messages or secrets here.
    error_code: Mapped[
        str | None
    ] = mapped_column(
        String(100),
        nullable=True,
    )

    # =========================================
    # Timestamps
    # =========================================

    # Always generated by SQL Server in UTC.
    #
    # TODATETIMEOFFSET is used so SQL Server
    # stores a datetimeoffset with +00:00.
    created_at: Mapped[
        datetime
    ] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=text(
            "TODATETIMEOFFSET("
            "SYSUTCDATETIME(), "
            "'+00:00'"
            ")"
        ),
    )

    completed_at: Mapped[
        datetime | None
    ] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )